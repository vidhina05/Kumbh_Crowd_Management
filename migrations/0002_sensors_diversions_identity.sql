-- 0002: crowd sensors and crowd history, gates, batch diversions, shifts and handover,
-- staff two-step sign-in (TOTP), Aadhaar Secure QR identity, opt-in face matching.

-- Ghats: position on the control-room map, safe limit, and a status (a gate can be held).
ALTER TABLE ghats ADD COLUMN map_x real NOT NULL DEFAULT 50;
ALTER TABLE ghats ADD COLUMN map_y real NOT NULL DEFAULT 50;
ALTER TABLE ghats ADD COLUMN safe_limit_pct integer NOT NULL DEFAULT 80 CHECK (safe_limit_pct BETWEEN 10 AND 100);
ALTER TABLE ghats DROP CONSTRAINT IF EXISTS ghats_occupancy_source_check;
ALTER TABLE ghats ADD CONSTRAINT ghats_occupancy_source_check CHECK (occupancy_source IN ('manual', 'sensor', 'simulated'));

CREATE TABLE gates (
  id text PRIMARY KEY,                       -- "sangam-g3"
  ghat_id text NOT NULL REFERENCES ghats(id) ON DELETE CASCADE,
  name text NOT NULL,                        -- "Gate 3"
  kind text NOT NULL DEFAULT 'both' CHECK (kind IN ('entry', 'exit', 'both')),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'held', 'closed')),
  map_x real NOT NULL DEFAULT 50,
  map_y real NOT NULL DEFAULT 50,
  status_changed_at timestamptz,
  status_changed_by uuid REFERENCES admin_users(id) ON DELETE SET NULL
);
CREATE INDEX gates_ghat ON gates (ghat_id);

-- Crowd sensors. Each device has its own key (only a hash is stored).
-- is_simulated sensors are generated by the built-in simulator and are always labelled "Simulated".
CREATE TABLE sensors (
  id text PRIMARY KEY,                       -- "S-0001"
  name text NOT NULL,
  kind text NOT NULL CHECK (kind IN ('gate_counter', 'zone_counter', 'camera_counter')),
  ghat_id text NOT NULL REFERENCES ghats(id) ON DELETE CASCADE,
  gate_id text REFERENCES gates(id) ON DELETE SET NULL,
  key_hash text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  is_simulated boolean NOT NULL DEFAULT false,
  last_seen_at timestamptz,
  last_reading jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sensors_ghat ON sensors (ghat_id);

CREATE TABLE sensor_readings (
  id bigserial PRIMARY KEY,
  sensor_id text NOT NULL REFERENCES sensors(id) ON DELETE CASCADE,
  at timestamptz NOT NULL,
  people_in integer CHECK (people_in IS NULL OR people_in >= 0),
  people_out integer CHECK (people_out IS NULL OR people_out >= 0),
  occupancy integer CHECK (occupancy IS NULL OR occupancy >= 0),
  source text NOT NULL CHECK (source IN ('sensor', 'simulated'))
);
CREATE INDEX sensor_readings_sensor_at ON sensor_readings (sensor_id, at);
CREATE INDEX sensor_readings_at ON sensor_readings (at);

-- Every change of a ghat's crowd number, from any source. Drives charts, projections and the shift report.
CREATE TABLE crowd_history (
  id bigserial PRIMARY KEY,
  ghat_id text NOT NULL REFERENCES ghats(id) ON DELETE CASCADE,
  at timestamptz NOT NULL DEFAULT now(),
  occupancy integer NOT NULL CHECK (occupancy >= 0),
  inflow_per_min real,
  outflow_per_min real,
  source text NOT NULL CHECK (source IN ('manual', 'sensor', 'simulated'))
);
CREATE INDEX crowd_history_ghat_at ON crowd_history (ghat_id, at);
CREATE INDEX crowd_history_at ON crowd_history (at);

-- Batch diversions: move families booked on batches at one ghat to another ghat.
CREATE TABLE diversions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code text NOT NULL UNIQUE,                 -- "D-0007"
  from_ghat_id text NOT NULL REFERENCES ghats(id),
  to_ghat_id text NOT NULL REFERENCES ghats(id),
  day date NOT NULL,
  reason text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'awaiting_approval' CHECK (status IN ('awaiting_approval', 'sent', 'rejected', 'undone')),
  families_count integer NOT NULL DEFAULT 0,
  people_count integer NOT NULL DEFAULT 0,
  projection jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_by uuid REFERENCES admin_users(id) ON DELETE SET NULL,
  approved_by uuid REFERENCES admin_users(id) ON DELETE SET NULL,
  approved_at timestamptz,
  sent_at timestamptz,
  undone_by uuid REFERENCES admin_users(id) ON DELETE SET NULL,
  undone_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT diversions_different_ghats CHECK (from_ghat_id <> to_ghat_id)
);
CREATE INDEX diversions_created ON diversions (created_at);

CREATE TABLE diversion_moves (
  diversion_id uuid NOT NULL REFERENCES diversions(id) ON DELETE CASCADE,
  family_id uuid NOT NULL REFERENCES families(id) ON DELETE CASCADE,
  from_slot_id uuid NOT NULL REFERENCES slots(id),
  to_slot_id uuid NOT NULL REFERENCES slots(id),
  people integer NOT NULL,
  sms_status text NOT NULL DEFAULT 'not_sent' CHECK (sms_status IN ('not_sent', 'sent', 'failed', 'not_connected')),
  confirmed_at timestamptz,
  PRIMARY KEY (diversion_id, family_id)
);

CREATE TABLE diversion_events (
  id bigserial PRIMARY KEY,
  diversion_id uuid NOT NULL REFERENCES diversions(id) ON DELETE CASCADE,
  at timestamptz NOT NULL DEFAULT now(),
  kind text NOT NULL,
  message text NOT NULL,
  actor_id uuid REFERENCES admin_users(id) ON DELETE SET NULL
);
CREATE INDEX diversion_events_div ON diversion_events (diversion_id, at);

-- Shifts and handover.
CREATE TABLE shifts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES admin_users(id) ON DELETE CASCADE,
  control_room text NOT NULL DEFAULT 'Sangam Control',
  started_at timestamptz NOT NULL DEFAULT now(),
  ended_at timestamptz,
  handover_to uuid REFERENCES admin_users(id) ON DELETE SET NULL,
  handover_notes text NOT NULL DEFAULT '',
  summary jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX shifts_user ON shifts (user_id, started_at);

-- Staff two-step sign-in (TOTP, RFC 6238). The secret is encrypted like other personal data.
ALTER TABLE admin_users ADD COLUMN mfa_secret_enc text;
ALTER TABLE admin_users ADD COLUMN mfa_enabled boolean NOT NULL DEFAULT false;
ALTER TABLE admin_users ADD COLUMN mfa_last_step bigint NOT NULL DEFAULT 0;
ALTER TABLE admin_users ADD COLUMN phone_enc text;

-- Identity: how the family leader was verified, and an Aadhaar reference that can't be reversed.
ALTER TABLE families ADD COLUMN id_method text NOT NULL DEFAULT 'phone' CHECK (id_method IN ('phone', 'aadhaar'));
ALTER TABLE families ADD COLUMN phone_verified boolean NOT NULL DEFAULT true;
ALTER TABLE families ADD COLUMN aadhaar_ref_hash text;
ALTER TABLE families ADD COLUMN aadhaar_last4 text;
ALTER TABLE families ADD COLUMN face_consent boolean NOT NULL DEFAULT false;
CREATE INDEX families_aadhaar_ref ON families (aadhaar_ref_hash);

-- Opt-in face template: a 1024-number description of the face (not the photo), encrypted.
ALTER TABLE members ADD COLUMN face_template_enc text;
ALTER TABLE members ADD COLUMN gender text CHECK (gender IS NULL OR gender IN ('M', 'F', 'T'));

-- Lost & found: photo of a found person (encrypted), timestamps for the reunion timeline, face-match suggestions.
ALTER TABLE lost_cases ADD COLUMN found_photo_enc text;
ALTER TABLE lost_cases ADD COLUMN found_at timestamptz;
ALTER TABLE lost_cases ADD COLUMN found_location text NOT NULL DEFAULT '';
ALTER TABLE lost_cases ADD COLUMN reunited_at timestamptz;
ALTER TABLE lost_cases ADD COLUMN thanks_sent_at timestamptz;

CREATE TABLE face_matches (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  lost_case_id uuid NOT NULL REFERENCES lost_cases(id) ON DELETE CASCADE,
  member_id uuid NOT NULL REFERENCES members(id) ON DELETE CASCADE,
  score real NOT NULL,
  status text NOT NULL DEFAULT 'suggested' CHECK (status IN ('suggested', 'confirmed', 'rejected')),
  reviewed_by uuid REFERENCES admin_users(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX face_matches_case ON face_matches (lost_case_id);

-- Kiosks on the map.
ALTER TABLE kiosks ADD COLUMN map_x real;
ALTER TABLE kiosks ADD COLUMN map_y real;
