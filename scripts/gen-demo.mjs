// Generates the route table and migration list for the in-browser demo backend.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const apiDir = path.join(root, "src/app/api");
const routes = [];
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = path.join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (f === "route.ts") routes.push(path.relative(path.join(root, "src/app"), path.dirname(p)).split(path.sep).join("/"));
  }
})(apiDir);
routes.sort();
// The retention cron is a server job; the voice proxy needs server keys. Neither runs in a browser.
const skip = new Set(["api/cron/retention"]);
const list = routes.filter((r) => !skip.has(r));
const lines = list.map((r, i) => `import * as r${i} from "@/app/${r}/route";`);
lines.push("", "export const ROUTES: { path: string; mod: Record<string, unknown> }[] = [");
list.forEach((r, i) => lines.push(`  { path: "/${r}", mod: r${i} },`));
lines.push("];", "");
writeFileSync(path.join(root, "src/demo/routes.generated.ts"), "// Generated by scripts/gen-demo.mjs — do not edit.\n" + lines.join("\n"));

const migDir = path.join(root, "migrations");
const migs = readdirSync(migDir).filter((f) => f.endsWith(".sql")).sort();
const out = ["// Generated by scripts/gen-demo.mjs — do not edit.", "export const MIGRATIONS: [string, string][] = ["];
for (const m of migs) out.push(`  [${JSON.stringify(m)}, ${JSON.stringify(readFileSync(path.join(migDir, m), "utf8"))}],`);
out.push("];", "");
writeFileSync(path.join(root, "src/demo/migrations.generated.ts"), out.join("\n"));
console.log(`demo: ${list.length} routes, ${migs.length} migrations`);
